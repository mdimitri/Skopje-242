def slug(text):
    """„Шмекер 42“ / „shmeker-42“ -> 'shmeker42'; None when it is not word + number."""
    t = "".join(_T.get(c, c) for c in (text or "").strip().lower())
    t = re.sub(r"[\s\-_.,]+", "", t)
    m = re.fullmatch(r"([a-z]{3,20})(\d{1,3})", t)
    return m.group(1) + m.group(2) if m else None


def pick(rng=random):
    w = rng.choice(WORDS)
    return "%s %d" % (w, rng.randrange(10, 100))
