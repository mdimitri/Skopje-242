def profile(hid):
    r = _P[hid]
    title, story, quote = hero_stories.S[hid]
    return dict(title=title, role=r[0], money=r[1], stats=dict(zip(STAT_KEYS, r[2])), quote=quote, story=story, goal=r[5],
                ability_name=r[6], ability=r[7], weakness=r[8])


def stat(hid, key, default=50):
    r = _P.get(hid)
    return r[2][STAT_KEYS.index(key)] if r else default


def susp_line(v):
    for lim, s in SUSP_REACT:
        if v <= lim:
            return s
    return SUSP_REACT[-1][1]
